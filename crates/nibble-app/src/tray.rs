//! The menu bar icon: the Wedge as a template image, plus the Multiplier as text.
//!
//! When the Wedge changes, the icon glides to the new one through a strip of fine frames:
//! the wedge shrinks a percent at a time, fades into crumbs, then into the paid-off
//! outline as its check draws in. It plays backwards when a new day starts.
//!
//! A dot in the top-left corner, where every frame is empty, says a new version is ready.

use std::sync::Mutex;
use std::thread;
use std::time::{Duration, Instant};

use nibble_core::{Combined, Wedge};
use tauri::image::Image;
use tauri::menu::{Menu, MenuItem};
use tauri::tray::{MouseButton, MouseButtonState, TrayIcon, TrayIconBuilder, TrayIconEvent};
use tauri::{AppHandle, Manager, Runtime, WebviewWindow};
use tauri_plugin_positioner::{Position, WindowExt};

use crate::view;

/// Every frame of the animation stacked top to bottom, generated by `design/scripts/gen.py`
/// as `design/menubar/strip.svg` and rendered at 36 pixels square (18 points at 2x).
const STRIP: &[u8] = include_bytes!("../icons/tray/strip.png");
/// A frame's width and height in pixels.
const SIDE: u32 = 36;
/// A frame's size in RGBA bytes.
const FRAME_BYTES: usize = 36 * 36 * 4;
/// How often a glide redraws: about 30 frames a second.
const TICK: Duration = Duration::from_millis(33);

/// The tray icon's id.
pub(crate) const ID: &str = "nibble";
/// The popover window's label, as in `tauri.conf.json`.
pub(crate) const POPOVER: &str = "popover";
/// How soon after the popover hid itself a click on the icon still counts as closing it.
/// Pressing the icon takes focus from the popover, which hides it before the click lands.
const CLOSING_CLICK: Duration = Duration::from_millis(400);

/// When the popover last hid itself because it lost focus.
#[derive(Default)]
struct Blurred(Mutex<Option<Instant>>);

/// What the animator should be showing, set by each refresh.
#[derive(Default)]
struct Goal {
    /// The resting frame of the current Wedge; `None` before the first verdict.
    frame: Option<usize>,
    /// The Multiplier label, shown once the icon arrives.
    title: Option<String>,
    /// Whether to show the update dot.
    badge: bool,
}

/// The animator's goal, shared with the refresh thread.
#[derive(Default)]
struct Animation(Mutex<Goal>);

/// Builds the tray icon with its click and menu behaviour.
pub(crate) fn build<R: Runtime>(app: &AppHandle<R>) -> tauri::Result<TrayIcon<R>> {
    app.manage(Animation::default());
    app.manage(Blurred::default());
    let frames = frames()?;
    let first = frames
        .first()
        .cloned()
        .unwrap_or_else(|| Image::new_owned(vec![0; FRAME_BYTES], SIDE, SIDE));
    let animator = app.clone();
    thread::spawn(move || animate(&animator, &frames));
    let quit = MenuItem::with_id(app, "quit", "Quit nibble", true, None::<&str>)?;
    let menu = Menu::with_items(app, &[&quit])?;
    TrayIconBuilder::with_id(ID)
        .icon(first)
        .icon_as_template(true)
        .tooltip("nibble")
        .menu(&menu)
        .show_menu_on_left_click(false)
        .on_menu_event(|handle, event| {
            if event.id() == "quit" {
                handle.exit(0);
            }
        })
        .on_tray_icon_event(|tray, event| {
            tauri_plugin_positioner::on_tray_event(tray.app_handle(), &event);
            if let TrayIconEvent::Click {
                button: MouseButton::Left,
                button_state: MouseButtonState::Up,
                ..
            } = event
            {
                toggle_popover(tray.app_handle());
            }
        })
        .build(app)
}

/// Shows the popover under the tray icon, or hides it if open.
fn toggle_popover<R: Runtime>(app: &AppHandle<R>) {
    let Some(window) = app.get_webview_window(POPOVER) else {
        return;
    };
    let blurred = app
        .state::<Blurred>()
        .0
        .lock()
        .ok()
        .and_then(|guard| *guard);
    if window.is_visible().unwrap_or(false) {
        let _hidden = window.hide();
    } else if !closed_by(blurred, Instant::now()) {
        show_popover(app, &window);
    }
}

/// Hides the popover when it loses focus, noting when, so the click that took the focus
/// does not open it again.
pub(crate) fn hide_on_blur<R: Runtime>(window: &tauri::Window<R>) {
    if let Ok(mut blurred) = window.app_handle().state::<Blurred>().0.lock() {
        *blurred = Some(Instant::now());
    }
    let _hidden = window.hide();
}

/// Whether a click at `now` is the one that hid the popover at `blurred`.
fn closed_by(blurred: Option<Instant>, now: Instant) -> bool {
    blurred.is_some_and(|at| now.saturating_duration_since(at) < CLOSING_CLICK)
}

/// Shows the popover under the tray icon without a click on it, e.g. from a notification.
pub(crate) fn open_popover<R: Runtime>(app: &AppHandle<R>) {
    let Some(window) = app.get_webview_window(POPOVER) else {
        return;
    };
    // The positioner learns where the icon is only from tray events, and none may have
    // come since launch, so tell it now.
    if let Some(tray) = app.tray_by_id(ID)
        && let Ok(Some(rect)) = tray.rect()
    {
        let event = TrayIconEvent::Move {
            id: tray.id().clone(),
            position: rect.position.to_physical(1.0),
            rect,
        };
        tauri_plugin_positioner::on_tray_event(app, &event);
    }
    show_popover(app, &window);
}

fn show_popover<R: Runtime>(app: &AppHandle<R>, window: &WebviewWindow<R>) {
    let _moved = window.move_window(Position::TrayBottomCenter);
    let _shown = window.show();
    let _focused = window.set_focus();
    crate::shell::refresh_soon(app);
}

/// Points the icon at the combined verdict: the animator glides to the new Wedge, then
/// shows the Multiplier. The first verdict glides down from a whole wedge.
pub(crate) fn show<R: Runtime>(app: &AppHandle<R>, combined: &Combined) -> tauri::Result<()> {
    let Some(tray) = app.tray_by_id(ID) else {
        return Ok(());
    };
    let bound = if combined.has_unpriced { "≥" } else { "" };
    let label = combined
        .multiplier
        .map(|m| format!("{bound}{}", view::multiplier(m)));
    let tooltip = label.as_ref().map_or_else(
        || "nibble: eating through your plan".to_owned(),
        |m| format!("nibble: paid off, {m}"),
    );
    if let Ok(mut goal) = app.state::<Animation>().0.lock() {
        goal.frame = Some(frame_of(combined.wedge));
        goal.title = label;
    }
    tray.set_tooltip(Some(tooltip))
}

/// Shows or hides the dot that says a new version is ready.
pub(crate) fn badge<R: Runtime>(app: &AppHandle<R>, on: bool) {
    if let Ok(mut goal) = app.state::<Animation>().0.lock() {
        goal.badge = on;
    }
}

/// Resting frames in the strip.
const FULL: usize = 0;
const TWO_THIRDS: usize = 34;
const ONE_THIRD: usize = 67;
const CRUMBS: usize = 95;
const PAID_OFF: usize = 111;

/// The frame showing `wedge` at rest.
const fn frame_of(wedge: Option<Wedge>) -> usize {
    match wedge {
        Some(Wedge::Full) | None => FULL,
        Some(Wedge::TwoThirds) => TWO_THIRDS,
        Some(Wedge::OneThird) => ONE_THIRD,
        Some(Wedge::Crumbs) => CRUMBS,
        Some(Wedge::PaidOff) => PAID_OFF,
    }
}

/// The strip cut into frames.
fn frames() -> tauri::Result<Vec<Image<'static>>> {
    let strip = Image::from_bytes(STRIP)?;
    Ok(strip
        .rgba()
        .as_chunks::<FRAME_BYTES>()
        .0
        .iter()
        .map(|frame| Image::new_owned(frame.to_vec(), SIDE, SIDE))
        .collect())
}

/// Runs for the app's lifetime: glides to each new goal and shows the title once there.
/// The icon rests between changes.
fn animate<R: Runtime>(app: &AppHandle<R>, frames: &[Image<'static>]) {
    let mut shown = 0;
    let mut titled = None;
    let mut badged = false;
    loop {
        let (target, title, badge) = app
            .state::<Animation>()
            .0
            .lock()
            .map(|goal| (goal.frame, goal.title.clone(), goal.badge))
            .unwrap_or_default();
        let Some(target) = target else {
            thread::sleep(TICK);
            continue;
        };
        if shown != target {
            glide(app, frames, shown, target, badge);
            shown = target;
            badged = badge;
        }
        if badged != badge {
            if let Some(image) = frames.get(shown) {
                let _drawn = draw(app, image, badge);
            }
            badged = badge;
        }
        if titled.as_ref() != Some(&title) {
            if let Some(tray) = app.tray_by_id(ID) {
                let _titled = tray.set_title(title.clone());
            }
            titled = Some(title);
        }
        thread::sleep(TICK);
    }
}

/// Moves the icon from frame `from` to `to`, easing in and out over a time that grows
/// with the distance.
fn glide<R: Runtime>(
    app: &AppHandle<R>,
    frames: &[Image<'static>],
    from: usize,
    to: usize,
    badge: bool,
) {
    let distance = from.abs_diff(to);
    let millis = (600 + 4 * u64::try_from(distance).unwrap_or(0)).min(1_500);
    let start = Instant::now();
    let mut drawn = None;
    loop {
        let elapsed = u64::try_from(start.elapsed().as_millis()).unwrap_or(u64::MAX);
        let permille = (elapsed * 1_000 / millis).min(1_000);
        let step = usize::try_from(eased(permille)).unwrap_or(1_000) * distance / 1_000;
        let frame = if from < to { from + step } else { from - step };
        if drawn != Some(frame) {
            if let Some(image) = frames.get(frame) {
                let _drawn = draw(app, image, badge);
            }
            drawn = Some(frame);
        }
        if permille == 1_000 {
            return;
        }
        thread::sleep(TICK);
    }
}

/// Cubic ease-in-out on a 0 to 1,000 scale.
const fn eased(t: u64) -> u64 {
    if t < 500 {
        4 * t * t * t / 1_000_000
    } else {
        let u = 2_000 - 2 * t;
        1_000 - u * u * u / 2_000_000
    }
}

fn draw<R: Runtime>(app: &AppHandle<R>, image: &Image<'static>, badge: bool) -> tauri::Result<()> {
    let Some(tray) = app.tray_by_id(ID) else {
        return Ok(());
    };
    let image = if badge {
        Image::new_owned(with_dot(image.rgba()), SIDE, SIDE)
    } else {
        image.clone()
    };
    // One call: setting the image and then the template flag flashes the raw black image.
    tray.set_icon_with_as_template(Some(image), true)
}

/// The dot's centre and radius, in eighths of a pixel: 5 points wide at 2x, its edge a
/// point clear of the frame's top and left.
const DOT_CENTRE: u32 = 6 * 8;
const DOT_RADIUS: u32 = 5 * 8;

/// `frame` with the update dot stamped in its top-left corner. Each pixel's opacity is the
/// share of its 16 sample points inside the circle, so the edge stays smooth.
fn with_dot(frame: &[u8]) -> Vec<u8> {
    let mut out = frame.to_vec();
    for (index, pixel) in out.as_chunks_mut::<4>().0.iter_mut().enumerate() {
        let index = u32::try_from(index).unwrap_or(u32::MAX);
        let (x, y) = (index % SIDE, index / SIDE);
        let mut inside = 0;
        for sx in 0..4 {
            for sy in 0..4 {
                let dx = (8 * x + 1 + 2 * sx).abs_diff(DOT_CENTRE);
                let dy = (8 * y + 1 + 2 * sy).abs_diff(DOT_CENTRE);
                if dx * dx + dy * dy <= DOT_RADIUS * DOT_RADIUS {
                    inside += 1;
                }
            }
        }
        let alpha = u8::try_from(inside * 255 / 16).unwrap_or(u8::MAX);
        if alpha > pixel[3] {
            *pixel = [0, 0, 0, alpha];
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use std::time::{Duration, Instant};

    use super::closed_by;

    #[test]
    fn a_click_right_after_the_popover_hid_itself_only_closes_it() {
        let blurred = Instant::now();
        assert!(closed_by(
            Some(blurred),
            blurred + Duration::from_millis(150)
        ));
    }

    #[test]
    fn a_later_click_opens_the_popover_again() {
        let blurred = Instant::now();
        assert!(!closed_by(Some(blurred), blurred + Duration::from_secs(2)));
        assert!(!closed_by(None, blurred));
    }
}
